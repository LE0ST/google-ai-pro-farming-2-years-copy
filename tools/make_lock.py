"""Build a fully pinned, hashed requirements lock that works on more than one OS.

`pip install --require-hashes` checks the hash of the file it actually selects.
Downloading wheels on the machine that ran the generator therefore bakes that
machine's platform into the lock: a darwin-arm64 lock dies on Linux with
"THESE PACKAGES DO NOT MATCH THE HASHES FROM THE REQUIREMENTS FILE".

This version asks the PyPI JSON API for every artifact published for the pinned
version and keeps the ones a Linux or macOS host could install: pure-python
wheels, manylinux/musllinux wheels, macOS wheels, and source distributions.
Windows wheels are skipped — this project does not run there, and they would
triple the file for nothing.

Modes::

    python tools/make_lock.py                # pins from .venv (pip freeze)
    python tools/make_lock.py --from-lock    # rebuild hashes for existing pins
    python tools/make_lock.py --verify       # check lock hashes against PyPI

No third-party imports: urllib, json, argparse.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VENV_PY = ROOT / ".venv" / "bin" / "python"
LOCK = ROOT / "requirements.lock"
PYPI = "https://pypi.org/pypi/{name}/{version}/json"

HEADER = (
    "# generated by tools/make_lock.py — do not edit by hand\n"
    "# platform: linux (manylinux/musllinux x86_64+aarch64) and darwin (arm64+x86_64)\n"
    "# python: 3.12+ — pip picks the artifact for this host and checks its hash\n"
)

_SKIP_TAGS = ("win32", "win_amd64", "win_arm64", "win_arm32")


def _wanted(filename: str) -> bool:
    if any(tag in filename for tag in _SKIP_TAGS):
        return False
    if filename.endswith((".tar.gz", ".zip")):
        return True
    if "none-any.whl" in filename:
        return True
    return "manylinux" in filename or "musllinux" in filename or "macosx" in filename


def _pins_from_venv() -> list[tuple[str, str]]:
    if not VENV_PY.exists():
        raise SystemExit(f"no venv at {VENV_PY} — create it first, or use --from-lock")
    raw = subprocess.run(
        [str(VENV_PY), "-m", "pip", "list", "--format=freeze"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.splitlines()
    out = []
    for line in raw:
        if "==" not in line or line.startswith("pip=="):
            continue
        name, _, version = line.partition("==")
        out.append((name.strip(), version.strip()))
    return out


def _pins_from_lock() -> list[tuple[str, str]]:
    if not LOCK.exists():
        raise SystemExit(f"no {LOCK} to read pins from")
    out = []
    for line in LOCK.read_text(encoding="utf-8").splitlines():
        line = line.strip().rstrip("\\").strip()
        if not line or line.startswith("#") or "==" not in line:
            continue
        name, _, rest = line.partition("==")
        out.append((name.strip(), rest.split()[0]))
    return out


def _hashes_for(name: str, version: str) -> tuple[list[str], dict[str, int]]:
    url = PYPI.format(name=name, version=version)
    try:
        with urllib.request.urlopen(url, timeout=45) as resp:  # noqa: S310
            data = json.load(resp)
    except urllib.error.HTTPError as exc:
        raise SystemExit(f"{name}=={version}: PyPI says {exc.code}") from exc
    counts = {"linux": 0, "macos": 0, "any": 0, "sdist": 0}
    hashes: set[str] = set()
    for f in data.get("urls", []):
        filename = f.get("filename", "")
        digest = (f.get("digests") or {}).get("sha256")
        if not digest or not _wanted(filename):
            continue
        hashes.add(digest)
        if filename.endswith((".tar.gz", ".zip")):
            counts["sdist"] += 1
        elif "none-any.whl" in filename:
            counts["any"] += 1
        elif "macosx" in filename:
            counts["macos"] += 1
        else:
            counts["linux"] += 1
    if not hashes:
        raise SystemExit(f"{name}=={version}: no linux/macos artifacts published")
    return sorted(hashes), counts


def build(pins: list[tuple[str, str]]) -> str:
    lines: list[str] = [HEADER.rstrip("\n")]
    for name, version in sorted(pins, key=lambda p: p[0].lower()):
        hashes, counts = _hashes_for(name, version)
        tag = " ".join(f"{k}={v}" for k, v in counts.items() if v)
        # The file itself carries no filenames, only hashes — record what the
        # hashes cover so a reviewer can see the lock is not single-platform.
        lines.append(f"# files: {tag}")
        if len(hashes) == 1:
            lines.append(f"{name}=={version} --hash=sha256:{hashes[0]}")
        else:
            lines.append(f"{name}=={version} \\")
            for digest in hashes[:-1]:
                lines.append(f"    --hash=sha256:{digest} \\")
            lines.append(f"    --hash=sha256:{hashes[-1]}")
        print(f"  {name}=={version}: {len(hashes)} artifacts ({tag})", file=sys.stderr)
    return "\n".join(lines) + "\n"


def verify() -> int:
    published = {name.lower(): set(_hashes_for(name, v)[0]) for name, v in _pins_from_lock()}

    listed: dict[str, list[str]] = {}
    current = ""
    for line in LOCK.read_text(encoding="utf-8").splitlines():
        stripped = line.strip().rstrip("\\").strip()
        if "==" in stripped and not stripped.startswith("#"):
            current = stripped.split("==")[0].strip().lower()
            listed.setdefault(current, [])
        elif stripped.startswith("--hash=sha256:"):
            listed.setdefault(current, []).append(stripped.split(":", 1)[1])

    bad = 0
    for name, hashes in sorted(listed.items()):
        if not hashes:
            print(f"FAIL {name}: no hashes pinned")
            bad += 1
            continue
        unknown = [h for h in hashes if h not in published.get(name, set())]
        if unknown:
            print(f"FAIL {name}: {len(unknown)} hashes not published on PyPI")
            bad += 1
    for name in published:
        if name not in listed:
            print(f"FAIL {name}: pinned on PyPI but missing from the lock")
            bad += 1
    print("--- verify ok" if not bad else f"--- {bad} problem(s)")
    return 1 if bad else 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--from-lock", action="store_true", help="reuse pins from requirements.lock")
    ap.add_argument("--verify", action="store_true", help="check existing lock against PyPI")
    args = ap.parse_args()

    if args.verify:
        return verify()

    pins = _pins_from_lock() if args.from_lock else _pins_from_venv()
    if not pins:
        raise SystemExit("no pins to write")
    LOCK.write_text(build(pins), encoding="utf-8")
    print(f"wrote {LOCK} with {len(pins)} pinned packages", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
